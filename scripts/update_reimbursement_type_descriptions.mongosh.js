const coll = db.reimbursement_types;
const now = new Date();
let modified = 0;
let missing = 0;

for (const [code, description] of Object.entries(TYPE_DESCRIPTIONS)) {
  const res = coll.updateOne(
    { code },
    { $set: { description, updatedAt: now } },
  );
  if (res.matchedCount === 0) {
    missing += 1;
    print(`未找到 code=${code}，跳过`);
  } else if (res.modifiedCount) {
    modified += 1;
  }
}

print(`description 更新完成: 修改 ${modified} 条, 未匹配 ${missing} 条`);
